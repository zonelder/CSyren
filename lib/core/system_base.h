#pragma once

#include <string_view>
#include <functional>
#include <memory>
#include <unordered_map>
#include "cstdmf/log.h"
#include "scene_context.h"
#include <optional>
#include "task_description.h"

namespace csyren::core
{
    template<class Derived> class TypedSystem;
    class OnceSystem;

    // Base of every system. Systems derive from TypedSystem<Derived> (per-frame
    // work, declared by the parameters of execute(), see typed_system.h) or from
    // OnceSystem (lifecycle only, never scheduled); the constructor is private
    // so a hand-written describe() is impossible.
    class System
    {
    public:
        virtual ~System() = default;
        System(const System&) = delete;
        System& operator=(const System&) = delete;

        void attach(SceneContext context)
        {
            _context.emplace(context);
            try { onAttach(); }
            catch (...) { onDetach(); _context.reset(); throw; }
        }
        void detach() noexcept
        {
            if (_context) { onDetach(); _context.reset(); }
        }
        bool attached() const noexcept { return _context.has_value(); }
        Scene* boundScene() const { return _context ? &_context->scene : nullptr; }

        // Lifecycle: run between frames on the owning main thread.
        virtual void init() {}
        virtual void shutdown() {}

        // The frame graph task (generated by TypedSystem). False for OnceSystem.
        virtual bool scheduled() const noexcept = 0;
        virtual TaskDescription describe() const = 0;
        // Runs the frame work once: SystemManager calls it from the frame graph;
        // tests may call it directly.
        void run() { runTask(); }

    protected:
        Scene& scene() const { return _context->scene; }
        EventBus& sceneBus() const { return _context->bus; }
        virtual void onAttach() {}
        virtual void onDetach() noexcept {}

    private:
        template<class Derived> friend class TypedSystem;
        friend class OnceSystem;
        System() = default;
        virtual void runTask() = 0;
        std::optional<SceneContext> _context;
    };

    // A system that only does lifecycle work (init/shutdown, attach/detach), e.g.
    // registering resource factories. It is configured like any system but never
    // enters the frame graph, so it cannot affect the schedule.
    class OnceSystem : public System
    {
    public:
        bool scheduled() const noexcept final { return false; }
        TaskDescription describe() const final { return {}; }
    protected:
        OnceSystem() = default;
    private:
        void runTask() final {}
    };

	namespace details
	{

		using SystemCreator = std::function<std::shared_ptr<System>()>;

		class SystemRegistry
		{
		public:
			static SystemRegistry& instance()
			{
				static SystemRegistry reg;
				return reg;
			}

			void registerSystem(std::string_view name, SystemCreator creator) 
			{
				_creators[std::string(name)] = std::move(creator);
			}

			std::shared_ptr<System> create(std::string_view name) {
				auto it = _creators.find(std::string(name));
				if (it != _creators.end()) {
					return it->second();
				}
				// Логирование ошибки: система не найдена
				log::error("attempt to create system {} but its not defined.\n", name);
				return nullptr;
			}

            bool contains(std::string_view name) const { return _creators.find(std::string(name)) != _creators.end(); }

		private:
			std::unordered_map<std::string, SystemCreator> _creators;
		};
	}
}

// Static self-registration for systems defined in a .cpp that is compiled
// straight into an executable (tests). Engine and project systems use the
// CS_SYSTEM marker (core/registration.h) instead.
#define REGISTER_SYSTEM(SystemClass) \
    namespace { \
        struct SystemClass##_Registrar { \
            SystemClass##_Registrar() { \
                ::csyren::core::details::SystemRegistry::instance().registerSystem( \
                    #SystemClass, \
                    []() -> std::shared_ptr<::csyren::core::System> { \
                        return std::make_shared<SystemClass>(); \
                    } \
                ); \
            } \
        }; \
        static SystemClass##_Registrar g_##SystemClass##_registrar; \
    }
